/**
 * Builds the Apps Script project in apps-script/dist:
 *   Engine.gs      src/engine bundled as a global `RailEngine` (the same code the website runs)
 *   Seed.gs        apps-script/seed/v8-seed.json as `V8_SEED`
 *   Code.gs, Setup.gs, QuotePdf.html, appsscript.json   copied from apps-script/src
 *
 * Usage: npm run build:apps-script   (then paste the files, or `clasp push` from apps-script/dist)
 */
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'rolldown';

const root = path.resolve(import.meta.dirname, '../..');
const src = path.join(root, 'apps-script/src');
const dist = path.join(root, 'apps-script/dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });

const banner = (what) =>
  `// GENERATED by scripts/apps-script/build.mjs from ${what}. Do not edit here: edit the source in the\n// sdg-railway-website repository and rebuild.\n`;

const out = await build({
  input: path.join(root, 'src/engine/index.ts'),
  output: { format: 'iife', name: 'RailEngine', file: path.join(dist, 'Engine.js') },
  write: false,
  // Apps Script V8 supports ES2019+ syntax.
  transform: { target: 'es2019' },
});
const code = out.output[0].code;
fs.writeFileSync(path.join(dist, 'Engine.gs'), banner('src/engine') + code);

const seed = JSON.parse(fs.readFileSync(path.join(root, 'apps-script/seed/v8-seed.json'), 'utf8'));
fs.writeFileSync(
  path.join(dist, 'Seed.gs'),
  banner('apps-script/seed/v8-seed.json') + `var V8_SEED = ${JSON.stringify(seed, null, 2)};\n`,
);

for (const f of fs.readdirSync(src)) fs.copyFileSync(path.join(src, f), path.join(dist, f));

const files = fs.readdirSync(dist).sort();
console.log(
  `apps-script/dist: ${files.join(', ')} (Engine.gs ${Math.round(code.length / 1024)} KB)`,
);
